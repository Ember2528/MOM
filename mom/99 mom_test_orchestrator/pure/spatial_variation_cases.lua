local function extremeFiniteWeights()
  expect(spatial.pick({1e308, 1e308}, 0.1) == 0
      and spatial.pick({1e308, 1e308}, 0.9) == 1,
    'overflowing finite totals must preserve equal probabilities')
  expect(spatial.pick({1e-300, 1e308, 1e308}, 0) == 0,
    'zero key must select the first positive weight even when scaling underflows')
  expect(spatial.pick({1e-320, 1e-320}, 0.25) == 0
      and spatial.pick({1e-320, 1e-320}, 0.75) == 1,
    'subnormal totals must preserve equal probabilities')
  local large = compile({gradients = {
    {axis = 'x', anchors = {{at = 0, weights = {1e308, 5e307, 0}}}},
    {axis = 'y', anchors = {{at = 0, weights = {1e308, 1e308, 0}}}},
  }})
  local largeWeights = spatial.resolveWeights(large, outside(0, 0))
  expect(spatial.pick(largeWeights, 0.5) == 0
      and spatial.pick(largeWeights, 0.8) == 1,
    'overflowing gradient products must preserve their relative weights')
  local wideRatio = compile({gradients = {
    {axis = 'x', anchors = {{at = 0, weights = {1e-300, 1e308, 0}}}},
    {axis = 'y', anchors = {{at = 0, weights = {1e-300, 1e308, 0}}}},
  }})
  local wideWeights = spatial.resolveWeights(wideRatio, outside(0, 0))
  expect(spatial.pick(wideWeights, 0) == 0,
    'zero key must retain a positive gradient product below the normalized range')
  local small = compile({gradients = {
    {axis = 'x', anchors = {{at = 0, weights = {1e-300, 2e-300, 0}}}},
    {axis = 'y', anchors = {{at = 0, weights = {1e-300, 1e-300, 0}}}},
  }})
  local smallWeights = spatial.resolveWeights(small, outside(0, 0))
  expect(spatial.pick(smallWeights, 0.2) == 0
      and spatial.pick(smallWeights, 0.5) == 1,
    'underflowing gradient products must preserve their relative weights')
  local subnormal = compile({gradients = {
    {axis = 'x', anchors = {{at = 0, weights = {1e-160, 2e-160, 0}}}},
    {axis = 'y', anchors = {{at = 0, weights = {1e-160, 1e-160, 0}}}},
  }})
  local subnormalWeights = spatial.resolveWeights(subnormal, outside(0, 0))
  expect(spatial.pick(subnormalWeights, 0.2) == 0
      and spatial.pick(subnormalWeights, 0.5) == 1,
    'subnormal gradient products must preserve their relative weights')
  for _, magnitude in ipairs({1e-200, 1e-160}) do
    local reciprocal = 1 / magnitude
    local restored = compile({gradients = {
      {axis = 'x', anchors = {{at = 0, weights = {magnitude, 1, 0}}}},
      {axis = 'x', anchors = {{at = 0, weights = {magnitude, 1, 0}}}},
      {axis = 'y', anchors = {{at = 0, weights = {reciprocal, 1, 0}}}},
      {axis = 'y', anchors = {{at = 0, weights = {reciprocal, 1, 0}}}},
    }})
    local restoredWeights = spatial.resolveWeights(restored, outside(0, 0))
    expect(math.abs(restoredWeights[1] - restoredWeights[2]) < 1e-12
        and spatial.pick(restoredWeights, 0.4) == 0
        and spatial.pick(restoredWeights, 0.6) == 1,
      'intermediate underflow must not change the final distribution')
    local overflow = compile({gradients = {
      {axis = 'x', anchors = {{at = 0, weights = {reciprocal, 1, 0}}}},
      {axis = 'x', anchors = {{at = 0, weights = {reciprocal, 1, 0}}}},
      {axis = 'y', anchors = {{at = 0, weights = {magnitude, 1, 0}}}},
      {axis = 'y', anchors = {{at = 0, weights = {magnitude, 1, 0}}}},
    }})
    local overflowWeights = spatial.resolveWeights(overflow, outside(0, 0))
    expect(math.abs(overflowWeights[1] - overflowWeights[2]) < 1e-12
        and spatial.pick(overflowWeights, 0.4) == 0
        and spatial.pick(overflowWeights, 0.6) == 1,
      'intermediate overflow must not change the final distribution')
  end
  local contradiction = compile({gradients = {
    {axis = 'x', anchors = {{at = 0, weights = {1e308, 0, 0}}}},
    {axis = 'x', anchors = {{at = 0, weights = {1e308, 0, 0}}}},
    {axis = 'y', anchors = {{at = 0, weights = {0, 1e308, 0}}}},
  }})
  local average = spatial.resolveWeights(contradiction, outside(0, 0))
  expect(spatial.pick(average, 0.5) == 0 and spatial.pick(average, 0.8) == 1,
    'contradictory gradients must average large finite weights safely')
  local minimum = 4.9406564584124654e-324
  local tinyContradiction = compile({gradients = {
    {axis = 'x', anchors = {{at = 0, weights = {minimum, 0, 0}}}},
    {axis = 'y', anchors = {{at = 0, weights = {0, minimum, 0}}}},
  }})
  local tinyAverage = spatial.resolveWeights(tinyContradiction, outside(0, 0))
  expect(spatial.pick(tinyAverage, 0.1) == 0 and spatial.pick(tinyAverage, 0.9) == 1,
    'contradictory gradients must retain the smallest finite weights')
  local unevenContradiction = compile({gradients = {
    {axis = 'x', anchors = {{at = 0, weights = {3 * minimum, 0, 0}}}},
    {axis = 'y', anchors = {{at = 0, weights = {0, 5 * minimum, 0}}}},
  }})
  local unevenAverage = spatial.resolveWeights(unevenContradiction, outside(0, 0))
  expect(spatial.pick(unevenAverage, 0.3) == 0
      and spatial.pick(unevenAverage, 0.4) == 1,
    'subnormal averages must preserve uneven relative weights')
  local interpolated = compile({gradients = {{axis = 'x', anchors = {
    {at = 1e308, weights = {1e308, 0, 0}},
    {at = -1e308, weights = {-1e308, 1e308, 0}},
  }}}})
  local weights = spatial.resolveWeights(interpolated, outside(0, 0))
  expect(weights[1] == 0 and weights[2] == 5e307,
    'interpolation must handle finite endpoints with an overflowing difference')
end

