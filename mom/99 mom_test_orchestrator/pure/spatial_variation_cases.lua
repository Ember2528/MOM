local function oversizedCircles()
  local profile = compile({
    default = {1, 0, 0},
    points = {
      {x = 0, y = 0, radius = 100000000, weights = {0, 0, 1}},
      {x = 0, y = 0, radius = 100, weights = {0, 1, 0}},
    },
  })
  expect(spatial.validate(profile, 2), 'large-circle fallback failed profile admission')
  expect(#profile.unindexedPoints == 1 and profile.unindexedPoints[1] == 1,
    'large circle was expanded into a map of exterior cells')
  local bucketCount = 0
  for _ in pairs(profile.pointBuckets) do bucketCount = bucketCount + 1 end
  expect(bucketCount == 4, 'large circle increased point-bucket storage')
  weightsEqual(spatial.resolveWeights(profile, outside(0, 0), {x = 1, y = 1}),
    {0, 0, 1}, 'indexed and fallback equal-distance tie preserves authored order')
  weightsEqual(spatial.resolveWeights(profile, outside(10000, 0), {x = 81920000, y = 1}),
    {0, 0, 1}, 'large circle still covers distant cells')
  weightsEqual(spatial.resolveWeights(profile, outside(12207, 0), {x = 100000000, y = 0}),
    {0, 0, 1}, 'large circle radius boundary')
  weightsEqual(spatial.resolveWeights(profile, outside(12207, 0), {x = 100000001, y = 0}),
    {1, 0, 0}, 'large circle does not become a rectangular region')
  -- The lower bound can still advance by one while the upper endpoint cannot.
  -- Numeric for loops must never expand either such precision-boundary circle.
  local edge = (2 ^ 53 - 1) * 8192
  local precise = compile({points = {
    {x = edge, y = 0, radius = 8192, weights = {0, 1, 0}},
    {x = 0, y = edge, radius = 8192, weights = {0, 0, 1}},
  }})
  expect(#precise.unindexedPoints == 2 and next(precise.pointBuckets) == nil,
    'precision-boundary circle entered an unsafe numeric bucket loop')
  weightsEqual(spatial.resolveWeights(precise, outside(2 ^ 53 - 1, 0), {x = edge, y = 0}),
    {0, 1, 0}, 'precision-boundary x circle remains available')
  weightsEqual(spatial.resolveWeights(precise, outside(0, 2 ^ 53 - 1), {x = 0, y = edge}),
    {0, 0, 1}, 'precision-boundary y circle remains available')
  local beyond = (2 ^ 53 + 4) * 8192
  local bounded = compile({points = {{x = beyond, y = beyond, radius = 8192, weights = {0, 1, 0}}}})
  expect(spatial.validate(bounded, 2), 'bounded precision-offset indexing produced an invalid profile')
  weightsEqual(spatial.resolveWeights(bounded, outside(2 ^ 53 + 4, 2 ^ 53 + 4),
    {x = beyond, y = beyond}), {0, 1, 0}, 'huge-coordinate circle survives bounded indexing')
end

