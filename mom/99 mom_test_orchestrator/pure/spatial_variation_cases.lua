local function pointPrecedenceAndBorders()
  local profile = compile({
    default = {1, 0, 0},
    regions = {test = {0, 0, 1}},
    cells = {{x = 0, y = 0, weights = {1, 1, 0}}, {x = 1, y = 0, weights = {1, 1, 0}}},
    points = {
      {x = 8192, y = 100, radius = 300, weights = {0, 1, 0}},
      {x = 8292, y = 100, radius = 300, weights = {0, 0, 1}},
    },
  })
  weightsEqual(spatial.resolveWeights(profile, outside(0, 0, 'test'), {x = 8191, y = 100}),
    {0, 1, 0}, 'point crossing left cell')
  weightsEqual(spatial.resolveWeights(profile, outside(1, 0, 'test'), {x = 8292, y = 100}),
    {0, 0, 1}, 'nearest overlapping point')
  weightsEqual(spatial.resolveWeights(profile, outside(1, 0, 'test'), {x = 8242, y = 100}),
    {0, 1, 0}, 'equal distance retains first point')
  weightsEqual(spatial.resolveWeights(profile, outside(1, 0, 'test'), {x = 8192, y = 400}),
    {0, 1, 0}, 'point includes its radius boundary')
  weightsEqual(spatial.resolveWeights(profile, outside(1, 0, 'test'), {x = 9000, y = 100}),
    {1, 1, 0}, 'outside circle falls back to cell')
end

