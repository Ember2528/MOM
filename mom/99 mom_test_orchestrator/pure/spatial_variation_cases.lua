local function keepAndWeightedBoundaries()
  expect(spatial.pick({1, 2, 3}, 0) == 0, 'first weight must mean KEEP')
  expect(spatial.pick({1, 2, 3}, 1 / 6) == 1, 'weight boundary must enter the next slot')
