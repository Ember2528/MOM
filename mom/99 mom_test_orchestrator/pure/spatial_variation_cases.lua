local function close(actual, expected, label)
  expect(math.abs(actual - expected) < 1e-12,
    tostring(label) .. ': ' .. tostring(actual) .. ' ~= ' .. tostring(expected))
end

local function weightsEqual(actual, expected, label)
  expect(#actual == #expected, tostring(label) .. ': wrong weight count')
  for i = 1, #expected do close(actual[i], expected[i], tostring(label) .. '[' .. i .. ']') end
end

local function compile(spec)
  local profile, reason = spatial.compile(spec, {variantCount = 2})
  expect(profile ~= nil, tostring(reason))
  return profile
end

local function outside(x, y, region)
  return {isExterior = true, gridX = x, gridY = y, region = region}
end

local function inside(name, region)
  return {isExterior = false, name = name, region = region}
end

