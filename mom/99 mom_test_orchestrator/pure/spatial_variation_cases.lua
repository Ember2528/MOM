local function persistenceAndSeedIsolation()
  local profile = compile({seed = -991, cluster = {
    scale = 2048, detail = 768, detailWeight = -0.3, jitter = 1.2,
  }, default = {1, 2, 3}})
  local snapshot = assert(plain_data.detach(profile))
  local changed = assert(plain_data.detach(profile))
  changed.seed = changed.seed + 1
  local differences = 0
  for i = -100, 100 do
    local cell = outside(math.floor(i / 10), 0)
    local position = {x = i * 173, y = -i * 593}
    local choice = spatial.choose(profile, cell, position)
    expect(choice == spatial.choose(snapshot, cell, position), 'plain save/reload changed variation')
    position.z, position.recordId = i, 'unrelated'
    expect(choice == spatial.choose(profile, cell, position), 'non-spatial identity changed variation')
    if choice ~= spatial.choose(changed, cell, position) then differences = differences + 1 end
  end
  expect(differences > 0, 'changing the seed did not change any choices')
  expect(plain_data.equalValidated(profile, snapshot), 'evaluation mutated the installed profile')
end

local function privateProfileValidation()
  local profile = compile({
    default = {1, 2, 3},
    points = {{x = 0, y = 0, radius = 10, weights = {0, 1, 0}}},
    gradients = {
      {axis = 'y', anchors = {{at = -1, weights = {0, 0, 1}}, {at = 1, weights = {1, 0, 0}}}},
    },
  })
  expect(spatial.validate(profile, 2), 'normalized profile was rejected')
  local mutations = {
    function(value) value.cluster.scale = 0 end,
    function(value) value.default[3] = nil end,
    function(value) value.seed = 1.5 end,
    function(value) value.gradients[1].anchors[1].at = -100 end,
    function(value) value.gradients[1].offsetAxis = 'x' end,
    function(value) value.gradients[1].anchors[1].weights[2] = math.huge end,
    function(value) value.points[1].radiusSquared = -1 end,
    function(value) value.pointBuckets['0,0'][1] = 2 end,
    function(value) value.interiors.home = {} end,
    function(value) value.climateOverrides.wet = {wetness = 'wet'} end,
  }
  for _, mutate in ipairs(mutations) do
    local invalid = assert(plain_data.detach(profile))
    mutate(invalid)
    local valid, message = spatial.validate(invalid, 2)
    expect(valid == nil and type(message) == 'string', 'malformed private profile was accepted')
  end
end

local function checkedNativeBuilder()
  local function rejects(spec, message, options)
    local ran, value, reason = pcall(spatial.compile, spec, options or {variantCount = 2})
    expect(ran and value == nil and type(reason) == 'string' and reason:find(message, 1, true),
      'expected checked builder rejection ' .. message .. ', got ' .. tostring(value or reason))
  end
  rejects(false, 'expected object')
  rejects({}, 'positive integer', {variantCount = 0})
  rejects({weights = {}}, 'field is not allowed')
  rejects({clustering = {}}, 'field is not allowed')
  rejects({cluster = false}, 'expected object')
  rejects({cluster = {detail_weight = 0.5}}, 'field is not allowed')
  rejects({cluster = {scale = 0}}, 'positive number')
  rejects({default = {1, 0}}, 'expected 3 weights')
  rejects({default = {1, math.huge, 0}}, 'finite')
  rejects({points = {{x = 0, y = 0, radius = 1e200, weights = {1, 0, 0}}}}, 'finite radius')
  rejects({points = false}, 'dense array')
  rejects({gradients = {{axis = 'latitude', anchors = {}}}}, 'unknown gradient axis')
  rejects({gradients = {{axis = 'x', anchors = {
    {at = 1, weights = {1, 0, 0}}, {at = 1, weights = {0, 1, 0}},
  }}}}, 'duplicate gradient anchor')
  rejects({gradients = {{axis = 'x', anchors = {}, offsetAxis = 'y'}}}, 'requires offsets')
  for _, field in ipairs({'regions', 'interiors', 'climateOverrides'}) do
    local value = field == 'regions' and {1, 0, 0}
      or (field == 'interiors' and {y = 0} or {wetness = 10})
    rejects({[field] = {REGION = value, region = value}}, 'duplicate normalized name region')
    rejects({[field] = false}, 'named object')
  end
  local cells = compile({cells = {
    {x = 1, y = -1, weights = {1, 0, 0}}, {x = 1, y = -1, weights = {0, 1, 0}},
  }})
  weightsEqual(spatial.resolveWeights(cells, outside(1, -1)), {0, 1, 0},
    'ordered duplicate cells retain their last entry')
end

